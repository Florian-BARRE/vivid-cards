import { describe, expect, it } from 'vitest';
import {
  GroupSource,
  PilotSource,
  addEntity,
  discover,
  moveEntity,
  parseSlot,
  readSlot,
  removeEntity,
  resolveSlot,
  setExcluded,
  setMode,
  writeSlot,
} from '../src/core/slots';
import type { HassEntity, HomeAssistant } from '../src/core/hass-types';
import { PilotIndex, nodeKey, parseNodeKey, type PilotTargetConfig } from '../src/core/pilot';

function entity(id: string, attributes: Record<string, unknown> = {}, state = 'on'): HassEntity {
  return { entity_id: id, state, attributes, last_changed: '', last_updated: '' };
}

function hassWith(states: HassEntity[], extra: Partial<HomeAssistant> = {}): HomeAssistant {
  return {
    states: Object.fromEntries(states.map((item) => [item.entity_id, item])),
    entities: {},
    devices: {},
    language: 'fr',
    callService: () => Promise.resolve(),
    ...extra,
  };
}

describe('slot values', () => {
  it('reads the four forms', () => {
    expect(parseSlot(undefined, 'x').mode).toBe('auto');
    expect(parseSlot(false, 'x').mode).toBe('off');
    expect(parseSlot('light.a', 'x')).toMatchObject({ mode: 'manual', manual: ['light.a'] });
    expect(parseSlot({ exclude: ['light.a'], add: ['light.b'] }, 'x')).toMatchObject({
      mode: 'auto',
      exclude: ['light.a'],
      add: ['light.b'],
    });
  });

  it('names the field in its errors', () => {
    expect(() => parseSlot(3, 'entities.presence')).toThrow(/entities\.presence/);
    expect(() => parseSlot(['nope'], 'lights')).toThrow(/lights\[0\]/);
    expect(() => parseSlot({ remove: [] }, 'lights')).toThrow(/exclude/);
    expect(readSlot(3).mode).toBe('auto');
  });

  it('writes the shortest value', () => {
    const auto = parseSlot(undefined, 'x');
    expect(writeSlot(auto, true)).toBeUndefined();
    expect(writeSlot(setExcluded(auto, 'light.a', true), true)).toEqual({ exclude: ['light.a'] });
    expect(
      writeSlot(setExcluded(setExcluded(auto, 'light.a', true), 'light.a', false), true),
    ).toBeUndefined();
    expect(writeSlot(setMode(auto, 'off', []), true)).toBe(false);
    expect(writeSlot(setMode(auto, 'manual', ['light.a', 'light.b']), true)).toEqual([
      'light.a',
      'light.b',
    ]);
    expect(writeSlot(setMode(auto, 'manual', ['sensor.a']), false)).toBe('sensor.a');
  });

  it('adds, moves and removes', () => {
    let slot = addEntity(parseSlot(undefined, 'x'), 'light.c', true);
    slot = addEntity(slot, 'light.d', true);
    expect(slot.add).toEqual(['light.c', 'light.d']);
    expect(moveEntity(slot, 'light.d', -1).add).toEqual(['light.d', 'light.c']);
    expect(removeEntity(slot, 'light.c').add).toEqual(['light.d']);
    expect(addEntity(parseSlot(undefined, 'x'), 'sensor.p', false)).toMatchObject({
      mode: 'manual',
      manual: ['sensor.p'],
    });
  });
});

describe('slot resolution', () => {
  const found = [
    { entity: 'light.a', source: 'pilot' as const, via: 'x' },
    { entity: 'light.b', source: 'pilot' as const, via: 'x' },
  ];

  it('keeps the found minus the left out, plus the added', () => {
    const slot = parseSlot({ exclude: ['light.a'], add: ['light.c'] }, 'x');
    const resolved = resolveSlot(slot, found, true);
    expect(resolved.entities).toEqual(['light.b', 'light.c']);
    expect(resolved.tweaked).toBe(true);
    expect(resolved.entries.map((entry) => [entry.entity, entry.origin, entry.excluded])).toEqual([
      ['light.a', 'found', true],
      ['light.b', 'found', false],
      ['light.c', 'added', false],
    ]);
  });

  it('leaves everything out with "*", and keeps one entity for a single slot', () => {
    expect(resolveSlot(parseSlot({ exclude: ['*'] }, 'x'), found, true).entities).toEqual([]);
    expect(resolveSlot(parseSlot(undefined, 'x'), found, false).entities).toEqual(['light.a']);
  });

  it('ignores the discovery when manual or off', () => {
    expect(resolveSlot(parseSlot(['light.z'], 'x'), found, true).entities).toEqual(['light.z']);
    expect(resolveSlot(parseSlot(false, 'x'), found, true).entities).toEqual([]);
  });
});

describe('Vivid Pilot', () => {
  const pilot = (node: string, kind: string, extra: Record<string, unknown> = {}) => ({
    vivid_pilot_node: node,
    vivid_pilot_kind: kind,
    ...extra,
  });
  const hass = hassWith(
    [
      entity(
        'light.vivid_pilot_salon_light',
        pilot('salon__light', 'group', { entity_id: ['switch.0xa1', 'light.hue_1'] }),
      ),
      entity('sensor.vivid_pilot_salon_temperature', pilot('salon__temperature', 'mean'), '21'),
      entity('sensor.vivid_pilot_salon_power', pilot('salon', 'power'), '40'),
      entity(
        'sensor.vivid_pilot_wled_tv_power',
        pilot('salon', 'strip_power', { light: 'light.wled_tv' }),
        '3',
      ),
      entity('sensor.vivid_pilot_all_battery', pilot('all__battery', 'battery'), '15'),
      entity('switch.0xa1'),
      entity('light.hue_1'),
      // Named like a room's sensor, but not generated by Vivid Pilot: never found.
      entity('binary_sensor.salon_presence', { friendly_name: 'salon-présence' }),
      entity('light.group', { entity_id: ['light.a', 'light.b'] }),
      entity('light.a'),
      entity('light.b'),
    ],
    {
      areas: {
        salon: { area_id: 'salon', name: 'Salon' },
        sdb: { area_id: 'sdb', name: 'Salle de bain' },
      },
    },
  );

  it('reads node keys', () => {
    expect(parseNodeKey('salon__light')).toEqual({ area: 'salon', category: 'light' });
    expect(parseNodeKey('all__battery')).toEqual({ area: undefined, category: 'battery' });
    expect(parseNodeKey('all')).toEqual({ area: undefined, category: undefined });
    expect(nodeKey('salon', 'light')).toBe('salon__light');
    expect(nodeKey(undefined)).toBe('all');
  });

  it('indexes what the integration generated, from its attributes only', () => {
    const index = PilotIndex.of(hass);
    expect(index.available).toBe(true);
    expect(index.entity('salon__light', 'group')).toBe('light.vivid_pilot_salon_light');
    expect(index.members('salon__light')).toEqual(['switch.0xa1', 'light.hue_1']);
    expect(index.locate('sensor.vivid_pilot_salon_power')).toEqual({
      node: 'salon',
      kind: 'power',
    });
    expect(index.stripPower('light.wled_tv')).toBe('sensor.vivid_pilot_wled_tv_power');
    expect(index.rooms()).toEqual([
      { area: 'salon', name: 'Salon', categories: ['light', 'temperature'] },
    ]);
    expect(index.homeCategories()).toEqual(['battery']);
    expect(PilotIndex.of(hass)).toBe(index);
  });

  it("finds a node's entity or its members, never by name", () => {
    expect(new PilotSource('salon__light', 'group').find(hass, { domains: [] })).toEqual([
      { entity: 'light.vivid_pilot_salon_light', source: 'pilot', via: 'salon__light' },
    ]);
    expect(
      new PilotSource('salon__light', 'group', true)
        .find(hass, { domains: ['switch'] })
        .map((item) => item.entity),
    ).toEqual(['switch.0xa1']);
    expect(new PilotSource('salon__presence', 'any').find(hass, { domains: [] })).toEqual([]);
  });

  it('expands groups and tries the sources in order', () => {
    expect(new GroupSource('light.group').find(hass, { domains: ['light'] })).toHaveLength(2);
    const order = [new PilotSource('sdb__light', 'group'), new GroupSource('light.group')];
    expect(discover(hass, order, { domains: [] })[0]?.source).toBe('group');
  });
});

describe('Pilot targets', () => {
  const target = (pilot: string): PilotTargetConfig => ({ pilot });
  const state = (entity_id: string, node: string, kind: string, extra = {}) => ({
    entity_id,
    state: '20',
    attributes: { vivid_pilot_node: node, vivid_pilot_kind: kind, ...extra },
    last_changed: '',
    last_updated: '',
  });
  const hass = {
    states: Object.fromEntries(
      [
        state('sensor.vivid_pilot_all_temperature', 'all__temperature', 'mean'),
        state('sensor.vivid_pilot_salon_temperature', 'salon__temperature', 'mean'),
        state('sensor.vivid_pilot_chambre_temperature', 'chambre__temperature', 'mean'),
        state('light.vivid_pilot_all_light', 'all__light', 'group'),
        state('light.vivid_pilot_salon_light', 'salon__light', 'group'),
      ].map((item) => [item.entity_id, item]),
    ),
    entities: {},
    devices: {},
    areas: {
      salon: { area_id: 'salon', name: 'Salon' },
      chambre: { area_id: 'chambre', name: 'Chambre' },
    },
    language: 'fr',
    callService: () => Promise.resolve(),
  } as HomeAssistant;

  it("stands for the node's entity, a hand-written entity winning", async () => {
    const { withPilotEntity } = await import('../src/core/pilot');
    expect(withPilotEntity(hass, target('salon__temperature'), 'mean').entity).toBe(
      'sensor.vivid_pilot_salon_temperature',
    );
    expect(
      withPilotEntity(hass, { pilot: 'salon__temperature', entity: 'sensor.x' }, 'mean').entity,
    ).toBe('sensor.x');
  });

  it('reads a home measure room by room, but keeps the home light group', async () => {
    const { withPilotEntity } = await import('../src/core/pilot');
    expect(withPilotEntity(hass, target('all__temperature'), 'mean').entities).toEqual([
      'sensor.vivid_pilot_chambre_temperature',
      'sensor.vivid_pilot_salon_temperature',
    ]);
    expect(withPilotEntity(hass, target('all__light'), 'group').entity).toBe(
      'light.vivid_pilot_all_light',
    );
  });
});
